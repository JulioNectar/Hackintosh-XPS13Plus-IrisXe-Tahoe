#!/usr/bin/env python3
# patch_vphal.py <plugin binary>: VPHAL kernel-table entry count 0x34B -> 0x34A and the derived struct sizes
# 0xD2C/0xD30 -> 0xD28/0xD2C (13 single-byte sites 0x5a7cc..0x5b01c), byte-identical to the WhateverXe Tahoe VA bundle.
# Target: "AVD error: GVAVPHALPPCreateContext, err = 11" (BGRA / PP output path).
import sys
p = sys.argv[1]; b = bytearray(open(p, 'rb').read())
S = [(0x5a7cc,0x4b,0x4a),(0x5a7d7,0x4b,0x4a),(0x5a807,0x2c,0x28),(0x5a835,0x4b,0x4a),(0x5a985,0x4b,0x4a),(0x5a990,0x4b,0x4a),
     (0x5a9b8,0x2c,0x28),(0x5a9d9,0x4b,0x4a),(0x5ad12,0x30,0x2c),(0x5ad7d,0x4b,0x4a),(0x5aeaf,0x4b,0x4a),(0x5afef,0x4b,0x4a),(0x5b01c,0x4b,0x4a)]
if all(b[o] == n for o, _, n in S): print('already patched'); sys.exit(0)
for o, old, new in S: assert b[o] == old, (hex(o), hex(b[o])); b[o] = new
open(p, 'wb').write(b); print('patched %d VPHAL sites' % len(S))
